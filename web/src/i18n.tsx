const pluralRules: Record<Lang, Intl.PluralRules> = {
  ar: new Intl.PluralRules('ar'),
  en: new Intl.PluralRules('en'),
};

/** "3 أسئلة", "سؤالان", "no questions" — grammatical count phrase for the current language. Numerals stay Latin. */
export function pluralize(lang: Lang, key: PluralKey, count: number): string {
  const forms: PluralForms = plurals[key][lang];
  const n = Math.max(0, Math.trunc(Number(count) || 0));
  const cat = pluralRules[lang].select(n) as keyof PluralForms;
  const form = forms[cat] ?? forms.other;
  return form.replace('{n}', String(n));
}

interface I18n {
  lang: Lang;
  dir: 'rtl' | 'ltr';
  t: (key: TKey) => string;
  /** count phrase with correct Arabic plural form — never build `count + noun` by hand */
  n: (key: PluralKey, count: number) => string;
  /** picks localized value from {ar, en} objects coming from the API */
  pick: (obj: unknown) => string;
  setLang: (l: Lang) => void;
}

const I18nContext = createContext<I18n>(null as never);

/** Persisted choice, else the browser locale (Arabic-first product). Shared with the pre-paint bootstrap in main.tsx. */
export function detectLang(): Lang {
  const saved = storageGet('lang');
  if (saved === 'ar' || saved === 'en') return saved;
  return typeof navigator !== 'undefined' && navigator.language?.toLowerCase().startsWith('ar') ? 'ar' : 'en';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(detectLang);
  const dir = lang === 'ar' ? 'rtl' : 'ltr';

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
  }, [lang, dir]);

  const value = useMemo<I18n>(
    () => ({
      lang,
      dir,
      t: (key) => dict[key]?.[lang] ?? dict[key]?.en ?? key,
      n: (key, count) => pluralize(lang, key, count),
      pick: (obj) => {
        if (typeof obj === 'string') return obj;
        if (obj && typeof obj === 'object') {
          const o = obj as Record<string, string>;
          return o[lang] || o.en || o.ar || '';
        }
        return '';
      },
      setLang: (l) => {
        storageSet('lang', l);
        setLangState(l);
      },
    }),
    [lang, dir],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

/** `tx('key', { n: 3 })`: a dictionary string with `{placeholders}` filled in. */
export function useTx(): (key: TKey, vars?: Record<string, string | number>) => string {
  const { t } = useI18n();
  return (key, vars) => {
    let out = t(key);
    if (vars) for (const [k, v] of Object.entries(vars)) out = out.split(`{${k}}`).join(String(v));
    return out;
  };
}

export function useI18n(): I18n {
  return useContext(I18nContext);
}
